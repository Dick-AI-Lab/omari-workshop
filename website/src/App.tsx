import { PresenterHUD, PresenterProvider, TopBar } from './components/shell';
import { ProvLegend } from './components/ui';
import { ArtifactProvider, useArtifacts } from './data/artifacts';
import { ImageSourceProvider } from './data/imageSource';
import Ch1Opening from './chapters/Ch1Opening';
import Ch2Data from './chapters/Ch2Data';
import Ch3Models from './chapters/Ch3Models';
import Ch4Evaluation from './chapters/Ch4Evaluation';
import Ch5Explain from './chapters/Ch5Explain';
import { Break, Ch6Detective, Ch7Closing } from './chapters/Ch6to7';

function BundleNotice() {
  const { status, manifest, error } = useArtifacts();
  if (status === 'ready') return <p className="small muted" style={{ fontFamily: 'var(--sans)' }}>Loaded artifact bundle <b>{manifest!.bundle_id}</b>, generated {manifest!.generated_at}.</p>;
  if (status === 'invalid') return <p className="small" style={{ fontFamily: 'var(--sans)', color: 'var(--p-missing)' }}>The artifact bundle could not be used: {error}.</p>;
  if (status === 'absent') return <p className="small muted" style={{ fontFamily: 'var(--sans)' }}>No model artifact bundle is loaded, so model-output figures show what is missing and how to produce it. All live simulations work.</p>;
  return null;
}

export default function App() {
  return (
    <ArtifactProvider>
      <ImageSourceProvider>
        <PresenterProvider>
          <TopBar />
          <main id="top">
            <header className="titleblock">
              <div className="series">Ottawa Medical AI Research Institute · Seminar Series</div>
              <h1><span className="from">From Pixels to Predictions</span>Developing AI models for medical image interpretation</h1>
              <p className="title-sub"><span>How do different ways of learning image representations change prediction, generalisation and explainability in prenatal ultrasound? An interactive two-hour workshop.</span></p>
              <div className="title-meta">
                <div><b>Task</b>Six-class maternal–fetal plane classification on FETAL_PLANES_DB</div>
                <div><b>Models</b>DenseNet-161 · ViT-B/16 · USF-MAE</div>
                <div><b>Format</b>120 minutes with a 10-minute break. Press <span className="kbd">P</span> to present.</div>
                <div><b>Reading the figures</b><BundleNotice /></div>
              </div>
              <div style={{ marginTop: '1.4rem' }}><ProvLegend /></div>
            </header>
            <div className="article">
              <Ch1Opening />
              <Ch2Data />
              <Ch3Models />
              <Ch4Evaluation />
              <Break />
              <Ch5Explain />
              <Ch6Detective />
              <Ch7Closing />
            </div>
          </main>
          <footer className="colophon">
            <p>Built for the OMARI Seminar Series. FETAL_PLANES_DB © Burgos-Artizzu et al., CC BY 4.0. Figures labelled “Model output” are generated by the repository’s export pipeline from trained checkpoints; figures labelled “Illustrative” are toy examples.</p>
            <p>Keyboard: ← → step through figures · [ ] chapters · P presenter mode · F fullscreen · T timer.</p>
          </footer>
          <PresenterHUD />
        </PresenterProvider>
      </ImageSourceProvider>
    </ArtifactProvider>
  );
}
